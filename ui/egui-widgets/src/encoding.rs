/// Every encoding a chart in this suite draws from.
///
/// # This vocabulary was already shared, it just wasn't named
///
/// `0x3987e5` ("value arriving") was written out as a literal in **thirteen**
/// modules and `0xe08a2e` ("value leaving") in seven — `flow_ring`,
/// `time_spine`, `flow_matrix`, `custody_walk`, `holder_field`,
/// `activity_lanes`, `party_annotator` and the rest. One vocabulary, maintained
/// by copy-paste, that no theme could move and no one could revise. Naming it
/// here is what makes both possible.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SeriesPalette {
    /// The categorical ramp, in assignment order. Distinguishable by hue;
    /// **never index this for a meaning** — that is what `ColorTokens` is for.
    ///
    /// **Five, and do not extend it.** Five is how many hues survive the
    /// adjacent-pair separation floors under both common dichromacies on a dark
    /// surface. The first draft of this struct carried six and the validator
    /// rejected it immediately — the sixth collapsed onto the first at ΔE 7.3
    /// under protanopia. A sixth series folds into [`Self::other`].
    pub categorical: [Color32; 5],
    /// The folded "everything else" band. Deliberately outside the categorical
    /// order so it never reads as one more series.
    pub other: Color32,
    /// **Nothing has been looked at yet** — deliberately distinct from a
    /// measured zero. Rendering "unknown" and "none" the same way is how a
    /// half-finished walk reads as a finished one.
    pub unobserved: Color32,
    /// Value arriving vs leaving — the direction encoding thirteen modules
    /// share.
    pub flow: Diverging,
    /// A short **ordinal classification**: how close a party is to the subject
    /// (`flow_ring`'s core / associate / customer). Innermost first; the fourth
    /// step is [`Self::unobserved`], because "nobody has looked" is the absence
    /// of a judgement rather than a fourth class.
    ///
    /// # Why this is enumerated when [`Sequential`] is generated
    ///
    /// Because its stops carry an **external** constraint, and no two-endpoint
    /// interpolation can be steered to meet one. These dots are drawn over
    /// chords painted in [`Self::flow`], and a seat must never be mistakable for
    /// a payment — violet, the obvious first pick, collapses onto the chord blue
    /// under protanopia at ΔE 5.1. A single-hue lightness ramp (which is what
    /// `Sequential` would give) was tried and failed differently: associate and
    /// customer measured ΔE 22 normal / 19 deutan, clearing the floor and still
    /// reading as one colour on 4px dots. The ramp moves in hue as well —
    /// pale aqua → green → deep teal — taking that pair to ΔE 53 / 44.
    ///
    /// So: generated where the only requirement is monotonicity, enumerated
    /// where the stops must also dodge colours outside the ramp. Both are
    /// checked; see `tests/series_palette.rs`.
    pub classes: [Color32; 3],
    /// Rank, depth, density: anything ordinal.
    pub ordinal: Sequential,
    /// The envelope for hashed identity colours.
    pub identity: IdentityEnvelope,
}

impl SeriesPalette {
    /// The values the suite already used, in their observed proportions.
    pub const fn tokyo_night() -> Self {
        Self {
            categorical: [
                Color32::from_rgb(0x39, 0x87, 0xe5),
                Color32::from_rgb(0xd9, 0x59, 0x26),
                Color32::from_rgb(0x19, 0x9e, 0x70),
                Color32::from_rgb(0xc9, 0x85, 0x00),
                Color32::from_rgb(0xd5, 0x51, 0x81),
            ],
            other: Color32::from_rgb(0x6b, 0x6b, 0x80),
            unobserved: Color32::from_rgb(0x4d, 0x54, 0x78),
            flow: Diverging {
                positive: Color32::from_rgb(0x39, 0x87, 0xe5),
                negative: Color32::from_rgb(0xe0, 0x8a, 0x2e),
                neutral: Color32::from_rgb(0x2a, 0x2e, 0x3f),
            },
            classes: [
                Color32::from_rgb(0xa5, 0xf3, 0xe4), // core — the subject itself
                Color32::from_rgb(0x3d, 0xdc, 0x84), // paid BY it
                Color32::from_rgb(0x0f, 0x8f, 0x8a), // bought FROM it
            ],
            ordinal: Sequential {
                low: Color32::from_rgb(0x3b, 0x40, 0x5a),
                high: Color32::from_rgb(0xff, 0xd7, 0x00),
            },
            identity: IdentityEnvelope {
                saturation: 0.75,
                lightness: 0.72,
            },
        }
    }

    /// Brighter and cooler, to sit on the marketplace palette's near-black.
    pub const fn opensea() -> Self {
        Self {
            categorical: [
                Color32::from_rgb(59, 142, 240),
                Color32::from_rgb(251, 146, 60),
                Color32::from_rgb(52, 199, 123),
                Color32::from_rgb(245, 181, 68),
                Color32::from_rgb(244, 88, 110),
            ],
            other: Color32::from_rgb(107, 107, 128),
            unobserved: Color32::from_rgb(71, 78, 92),
            flow: Diverging {
                positive: Color32::from_rgb(59, 142, 240),
                negative: Color32::from_rgb(251, 146, 60),
                neutral: Color32::from_rgb(34, 37, 44),
            },
            // Same aqua → green → teal band, brightened to this palette. The
            // band is not a style choice: it is the region that stays clear of
            // both chord colours under dichromacy, and the validator holds this
            // preset to it exactly as it holds the default.
            classes: [
                Color32::from_rgb(0xa7, 0xf3, 0xd0),
                Color32::from_rgb(0x34, 0xc7, 0x7b),
                Color32::from_rgb(0x0d, 0x87, 0x7b),
            ],
            ordinal: Sequential {
                low: Color32::from_rgb(45, 49, 58),
                high: Color32::from_rgb(56, 189, 248),
            },
            identity: IdentityEnvelope {
                saturation: 0.85,
                lightness: 0.75,
            },
        }
    }

    /// Series `i`, **folding** past the end of the ramp into [`Self::other`].
    ///
    /// Folding, not wrapping. Wrapping was the first draft and it is the worse
    /// failure: it makes series 0 and series 5 the *same colour* while both
    /// still claim to be data, which is precisely the collision the ramp is
    /// capped at five to avoid. A folded band is honest — it says "several
    /// things, not broken out".
    pub fn nth(&self, i: usize) -> Color32 {
        self.categorical.get(i).copied().unwrap_or(self.other)
    }

    /// Value arriving. Named for the encoding, not the hue.
    pub fn inbound(&self) -> Color32 {
        self.flow.positive
    }

    /// Value leaving.
    pub fn outbound(&self) -> Color32 {
        self.flow.negative
    }

    /// The classification tint for `ring`, saturating at [`Self::unobserved`].
    ///
    /// Saturating rather than wrapping for the same reason [`Self::nth`] folds:
    /// past the last named class there is no further judgement to show, and
    /// recycling `classes[0]` would claim one.
    pub fn class(&self, ring: u8) -> Color32 {
        self.classes
            .get(ring as usize)
            .copied()
            .unwrap_or(self.unobserved)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Round-tripping must not drift, or a ramp regenerated each frame would
    /// shimmer.
    #[test]
    fn oklab_round_trips_within_a_bit() {
        for c in [
            Color32::from_rgb(0x39, 0x87, 0xe5),
            Color32::from_rgb(255, 215, 0),
            Color32::from_rgb(12, 13, 16),
            Color32::WHITE,
        ] {
            let back = from_oklab(oklab(c));
            for (a, b) in [(c.r(), back.r()), (c.g(), back.g()), (c.b(), back.b())] {
                assert!(a.abs_diff(b) <= 1, "{c:?} -> {back:?}");
            }
        }
    }

    #[test]
    fn a_ramp_ends_where_it_says_it_does() {
        let s = SeriesPalette::tokyo_night().ordinal;
        assert_eq!(s.at(0.0), s.low);
        assert_eq!(s.at(1.0), s.high);
        // Out of range clamps rather than extrapolating into nonsense.
        assert_eq!(s.at(-5.0), s.low);
        assert_eq!(s.at(5.0), s.high);
    }

    #[test]
    fn rank_one_is_the_bright_end() {
        let s = SeriesPalette::tokyo_night().ordinal;
        assert_eq!(s.by_rank(0, 100), s.high);
        assert_eq!(s.by_rank(100, 100), s.low);
        // No total means nothing is ranked — recede, don't claim first place.
        assert_eq!(s.by_rank(1, 0), s.low);
    }

    #[test]
    fn diverging_sits_on_its_neutral_at_zero() {
        let d = SeriesPalette::tokyo_night().flow;
        assert_eq!(d.at(0.0), d.neutral);
        assert_eq!(d.at(1.0), d.positive);
        assert_eq!(d.at(-1.0), d.negative);
    }

    #[test]
    fn steps_covers_both_ends() {
        let s = SeriesPalette::tokyo_night().ordinal;
        assert!(s.steps(0).is_empty());
        assert_eq!(s.steps(1), vec![s.high]);
        let five = s.steps(5);
        assert_eq!(five.len(), 5);
        assert_eq!(five[0], s.low);
        assert_eq!(five[4], s.high);
    }

    /// The same identity must keep its colour across frames and sessions —
    /// these get compared between screenshots.
    #[test]
    fn identity_colour_is_stable_and_in_gamut() {
        let e = SeriesPalette::tokyo_night().identity;
        assert_eq!(e.color(12345), e.color(12345));
        assert_ne!(e.color(0), e.color(24)); // a third of the wheel apart
    }
}
