//! `arcade-room-worker` — a Cloudflare Durable Object that hosts one
//! [`arcade_room`] world.
//!
//! One Durable Object is one world shard of up to the sim's `MAX_SEATS`
//! players. [`RoomHost`] does everything but name the class: it accepts
//! WebSockets through the hibernation API, feeds binary frames to the
//! [`Room`], sends what the room returns, keeps the world's clock moving
//! with an alarm while anyone plays, and saves the world to Durable Object
//! storage every few seconds and whenever it pauses.
//!
//! A game's worker composes it: a class that holds a [`RoomHost`] and
//! delegates each handler to it, and a router. The class is written out in
//! the worker rather than generated by a macro here, because
//! `#[durable_object]` needs `worker::*` (and its `wasm_bindgen`) in scope
//! where it expands.
//!
//! ```ignore
//! use worker::*;
//! use island_sim::net::Island;
//!
//! #[durable_object]
//! pub struct IslandWorld { host: arcade_room_worker::RoomHost<Island> }
//!
//! impl DurableObject for IslandWorld {
//!     fn new(state: State, env: Env) -> Self { Self { host: RoomHost::new(state, env) } }
//!     async fn fetch(&self, req: Request) -> Result<Response> { self.host.fetch(req).await }
//!     async fn alarm(&self) -> Result<Response> { self.host.alarm().await }
//!     async fn websocket_message(&self, ws: WebSocket, m: WebSocketIncomingMessage) -> Result<()> {
//!         self.host.websocket_message(ws, m).await
//!     }
//!     async fn websocket_close(&self, ws: WebSocket, _: usize, _: String, _: bool) -> Result<()> {
//!         self.host.websocket_close(ws).await
//!     }
//! }
//!
//! #[event(fetch)]
//! async fn fetch(req: Request, env: Env, _ctx: Context) -> Result<Response> {
//!     // GET /ws/<world> upgrades to that world's shard.
//!     arcade_room_worker::connect::<Island>(req, &env, "WORLDS").await
//! }
//! ```
//!
//! # Shards are named by sim version
//!
//! A world's Durable Object is named `<game>/v<version>/<world>`. A deploy that
//! leaves the sim alone leaves every world running; a new sim version starts
//! new worlds, rather than restoring state the new code may step differently.
//!
//! # No timer while people play
//!
//! Every client sends at least a heartbeat every 100 ms, and each frame polls
//! the room's clock. The alarm (every second while seats are held) is a
//! backstop and the save timer. With no seats held, the alarm stops and the
//! object can hibernate.

use std::cell::RefCell;
use std::collections::BTreeMap;
use std::rc::Rc;
use std::time::Duration;

use arcade_room::{ConnId, Room, RoomConfig, RoomSim, To};
use worker::{
    Date, Env, Request, Response, Result, State, WebSocket, WebSocketIncomingMessage, WebSocketPair,
};

/// Storage key of the saved room.
const SAVE_KEY: &str = "room";
/// Ms between saves while the world runs.
const SAVE_EVERY_MS: u64 = 5_000;
/// Ms between backstop polls while seats are held.
const ALARM_MS: u64 = 1_000;
/// Close code for sockets left from before the object restarted: the client
/// should reconnect.
const RESTARTED: u16 = 1012;

/// Name of a world's Durable Object.
pub fn shard_name<S: RoomSim>(world: &str) -> String {
    format!("{}/v{}/{}", S::GAME, S::VERSION, world)
}

/// A world's seed, from its name: the same world name always generates the
/// same islands.
pub fn world_seed(world: &str) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in world.bytes() {
        h = (h ^ u64::from(b)).wrapping_mul(0x0100_0000_01b3);
    }
    h
}

fn now() -> u64 {
    Date::now().as_millis()
}

fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push(DIGITS[usize::from(b >> 4)] as char);
        s.push(DIGITS[usize::from(b & 15)] as char);
    }
    s
}

fn unhex(s: &str) -> Option<Vec<u8>> {
    let digit = |c: u8| (c as char).to_digit(16).map(|d| d as u8);
    s.as_bytes()
        .chunks(2)
        .map(|p| match p {
            [a, b] => Some(digit(*a)? << 4 | digit(*b)?),
            _ => None,
        })
        .collect()
}

struct Live<S: RoomSim> {
    room: Room<S>,
    sockets: BTreeMap<ConnId, WebSocket>,
    next_conn: ConnId,
    last_save: u64,
    was_running: bool,
}

/// The Durable Object's state for one world. Held by the class
/// [`world_object!`] declares.
pub struct RoomHost<S: RoomSim> {
    state: State,
    cfg: RoomConfig,
    /// Loaded on the first request after the object starts.
    live: RefCell<Option<Live<S>>>,
    /// Verifies a hello's session: see [`RoomHost::identify_with`].
    identify: Option<Verify>,
}

/// A session verifier, shared with each room the object loads.
type Verify = Rc<dyn Fn(&str) -> Option<String>>;

impl<S: RoomSim> RoomHost<S> {
    pub fn new(state: State, _env: Env) -> Self {
        Self {
            state,
            cfg: RoomConfig::default(),
            live: RefCell::new(None),
            identify: None,
        }
    }

    /// Seat players by verified identity: `verify` checks a hello's session
    /// token and returns who it names (`discord:<user id>`), or `None`. See
    /// [`Room::identify_with`] for what that changes. A game reads its
    /// verifying key from `env` when it builds the host:
    ///
    /// ```ignore
    /// let secret = env.secret("SESSION_SECRET")?.to_string();
    /// RoomHost::new(state, env).identify_with(move |token| verify(token, &secret))
    /// ```
    pub fn identify_with(mut self, verify: impl Fn(&str) -> Option<String> + 'static) -> Self {
        self.identify = Some(Rc::new(verify));
        self
    }

    /// Load the saved room once per object lifetime, or start the world
    /// named `world` if there is no save. With no name and no save (a socket
    /// message reaching a restarted object before any request), only close
    /// the stale sockets. Returns whether a room is live.
    async fn ensure(&self, world: Option<&str>) -> Result<bool> {
        if self.live.borrow().is_some() {
            return Ok(true);
        }
        let now = now();
        let saved: Option<String> = self.state.storage().get(SAVE_KEY).await?;
        let loaded = saved
            .as_deref()
            .and_then(unhex)
            .map(|bytes| Room::<S>::load(&bytes, self.cfg, now));
        let room = match (loaded, world) {
            (Some(Ok(room)), _) => Some(room),
            (Some(Err(why)), Some(world)) => {
                worker::console_error!("saved room did not load ({why}); starting afresh");
                Some(Room::new(world_seed(world), self.cfg))
            }
            (None, Some(world)) => Some(Room::new(world_seed(world), self.cfg)),
            (_, None) => None,
        };
        // Sockets accepted by an earlier instance of this object have no
        // seat in the room just loaded: ask their clients to reconnect.
        for ws in self.state.get_websockets() {
            let _ = ws.close(Some(RESTARTED), Some("world restarted; reconnect"));
        }
        let Some(mut room) = room else {
            return Ok(false);
        };
        if let Some(verify) = &self.identify {
            let verify = Rc::clone(verify);
            room.identify_with(Box::new(move |token| verify(token)));
        }
        *self.live.borrow_mut() = Some(Live {
            room,
            sockets: BTreeMap::new(),
            next_conn: 1,
            last_save: now,
            was_running: false,
        });
        Ok(true)
    }

    /// `/<world>` with `Upgrade: websocket`: seat a connection.
    /// `/<world>/status`: the room's counters, as text. [`connect`] sends
    /// both.
    pub async fn fetch(&self, req: Request) -> Result<Response> {
        let url = req.url()?;
        let mut parts = url.path().trim_start_matches('/').split('/');
        let world = parts.next().filter(|w| !w.is_empty()).unwrap_or("main");
        let status = parts.next() == Some("status");
        self.ensure(Some(world)).await?;
        if status {
            let live = self.live.borrow();
            let live = live.as_ref().expect("ensured");
            return Response::ok(format!(
                "{} v{}: tick {}, {} seated, {} real connected, running {}\n{:?}\n",
                S::GAME,
                S::VERSION,
                live.room.sim().tick(),
                live.room.seated(),
                live.room.real_connected(),
                live.room.running(),
                live.room.stats(),
            ));
        }
        let upgrade = req.headers().get("Upgrade")?.unwrap_or_default();
        if !upgrade.eq_ignore_ascii_case("websocket") {
            return Response::error("expected a WebSocket upgrade", 426);
        }
        let WebSocketPair { client, server } = WebSocketPair::new()?;
        self.state.accept_web_socket(&server);
        let conn = {
            let mut live = self.live.borrow_mut();
            let live = live.as_mut().expect("ensured");
            let conn = live.next_conn;
            live.next_conn += 1;
            live.room.open(conn);
            live.sockets.insert(conn, server.clone());
            conn
        };
        server.serialize_attachment(conn)?;
        self.schedule().await?;
        Response::from_websocket(client)
    }

    /// Players newly seated since the last call, and the key each holds their
    /// seat under: see [`Room::take_joined`]. Empty before the room loads.
    ///
    /// The hooks below are for a game that keeps something about its players
    /// outside the world (saved progress): its Durable Object calls the
    /// host's handlers, then these, around its own storage.
    pub fn take_joined(&self) -> Vec<(arcade_room::Seat, String)> {
        self.live
            .borrow_mut()
            .as_mut()
            .map(|l| l.room.take_joined())
            .unwrap_or_default()
    }

    /// Tell the world what the game keeps about `player`: a
    /// [`arcade_room::Change::Profile`] on their seat at the next tick. See
    /// [`Room::profile`].
    pub fn profile(&self, player: &str, bytes: Vec<u8>) -> bool {
        self.live
            .borrow_mut()
            .as_mut()
            .is_some_and(|l| l.room.profile(player, bytes))
    }

    /// Read the room: its confirmed world and who holds each seat. `None`
    /// before it loads.
    pub fn read<R>(&self, f: impl FnOnce(&Room<S>) -> R) -> Option<R> {
        self.live.borrow().as_ref().map(|l| f(&l.room))
    }

    /// The object's storage, for what a game keeps beside the room (under
    /// keys other than the room's own, `"room"`).
    pub fn storage(&self) -> worker::Storage {
        self.state.storage()
    }

    fn conn_of(ws: &WebSocket) -> Option<ConnId> {
        ws.deserialize_attachment::<ConnId>().ok().flatten()
    }

    pub async fn websocket_message(
        &self,
        ws: WebSocket,
        message: WebSocketIncomingMessage,
    ) -> Result<()> {
        let WebSocketIncomingMessage::Binary(bytes) = message else {
            return Ok(());
        };
        let Some(conn) = Self::conn_of(&ws) else {
            return Ok(());
        };
        if self.live.borrow().is_none() {
            // A socket from before a restart: ensure() closes it, and its
            // client reconnects and says hello afresh.
            self.ensure(None).await?;
            return Ok(());
        }
        {
            let mut live = self.live.borrow_mut();
            let live = live.as_mut().expect("checked");
            live.room.message(conn, &bytes, now());
        }
        self.flush();
        self.after().await
    }

    pub async fn websocket_close(&self, ws: WebSocket) -> Result<()> {
        if let Some(conn) = Self::conn_of(&ws)
            && let Some(live) = self.live.borrow_mut().as_mut()
        {
            live.sockets.remove(&conn);
            live.room.close(conn, now());
        }
        self.flush();
        self.after().await
    }

    pub async fn alarm(&self) -> Result<Response> {
        if let Some(live) = self.live.borrow_mut().as_mut() {
            live.room.poll(now());
        }
        self.flush();
        self.after().await?;
        self.schedule().await?;
        Response::ok("")
    }

    /// Send what the room has queued.
    fn flush(&self) {
        let mut live = self.live.borrow_mut();
        let Some(live) = live.as_mut() else { return };
        for out in live.room.drain() {
            let conns = match out.to {
                To::One(c) => vec![c],
                To::Many(cs) => cs,
            };
            for conn in conns {
                if let Some(ws) = live.sockets.get(&conn) {
                    let _ = ws.send_with_bytes(&out.bytes);
                    if out.close {
                        let _ = ws.close(Some(1008), Some("refused"));
                        live.sockets.remove(&conn);
                    }
                }
            }
        }
    }

    /// Save on a pause, and every few seconds while running.
    async fn after(&self) -> Result<()> {
        let save = {
            let mut live = self.live.borrow_mut();
            let Some(live) = live.as_mut() else {
                return Ok(());
            };
            let now = now();
            let running = live.room.running();
            let paused = live.was_running && !running;
            live.was_running = running;
            let due = running && now >= live.last_save + SAVE_EVERY_MS;
            if paused || due {
                live.last_save = now;
                Some(hex(&live.room.save()))
            } else {
                None
            }
        };
        if let Some(save) = save {
            self.state.storage().put(SAVE_KEY, save).await?;
        }
        Ok(())
    }

    /// Keep an alarm set while any seat is held: the backstop poll, and what
    /// expires a dropped player's grace when nobody else is sending.
    async fn schedule(&self) -> Result<()> {
        let held = self
            .live
            .borrow()
            .as_ref()
            .is_some_and(|l| l.room.seated() > 0 || !l.sockets.is_empty());
        if held {
            if self.state.storage().get_alarm().await?.is_none() {
                self.state
                    .storage()
                    .set_alarm(Duration::from_millis(ALARM_MS))
                    .await?;
            }
        } else {
            self.state.storage().delete_alarm().await?;
        }
        Ok(())
    }
}

/// Route `GET …/ws/<world>` (a WebSocket upgrade) and `GET …/status/<world>`
/// to the world's shard, in the Durable Object namespace bound as `binding`.
/// World names are letters, digits, `-` and `_`, up to 32 of them.
pub async fn connect<S: RoomSim>(req: Request, env: &Env, binding: &str) -> Result<Response> {
    let url = req.url()?;
    let mut parts = url.path().rsplit('/');
    let world = parts.next().unwrap_or_default().to_string();
    let kind = parts.next().unwrap_or_default();
    let valid = !world.is_empty()
        && world.len() <= 32
        && world
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_');
    if !valid || !matches!(kind, "ws" | "status") {
        return Response::error("expected /ws/<world> or /status/<world>", 404);
    }
    let stub = env
        .durable_object(binding)?
        .id_from_name(&shard_name::<S>(&world))?
        .get_stub()?;
    let path = if kind == "status" {
        format!("https://world/{world}/status")
    } else {
        format!("https://world/{world}")
    };
    let mut forward = Request::new(&path, worker::Method::Get)?;
    for (k, v) in req.headers() {
        forward.headers_mut()?.set(&k, &v)?;
    }
    stub.fetch_with_request(forward).await
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_save_round_trips_through_hex() {
        let bytes: Vec<u8> = (0..=255).collect();
        assert_eq!(unhex(&hex(&bytes)), Some(bytes));
        assert_eq!(unhex("abc"), None);
        assert_eq!(unhex("zz"), None);
    }

    #[test]
    fn a_worlds_seed_is_its_names() {
        assert_eq!(world_seed("main"), world_seed("main"));
        assert_ne!(world_seed("main"), world_seed("other"));
    }
}
